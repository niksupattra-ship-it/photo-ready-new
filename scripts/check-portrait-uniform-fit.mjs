import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('../src/portrait-uniform-fit.js',import.meta.url),'utf8');
const {measureUniformAnchors,planPortraitUniformFit}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const pixels=new Uint8ClampedArray(300*400*4);
for(let y=80;y<400;y++)for(let x=30;x<270;x++)if(y>=150||x<125||x>175)pixels[(y*300+x)*4+3]=255;
const uniform=measureUniformAnchors(pixels,300,400);
assert.equal(uniform.socketY,150);assert.equal(uniform.centerX,149.5);
const input={W:900,H:1200,uniform,frame:{x:0,y:300,w:900,h:1200},face:{width:1000,height:1200,cx:500,chinY:850,faceWidth:400,faceHeight:500,eyeWidth:250},opaqueTop:100};
const fit=planPortraitUniformFit(input);
assert(Math.abs(fit.hX+500*fit.scale-fit.collarCX)<1e-6);
assert(fit.hY+850*fit.scale<fit.collarSocketY);
assert(fit.hY+100*fit.scale>=54-1e-6);
const enlarged=planPortraitUniformFit({...input,face:Object.fromEntries(Object.entries(input.face).map(([k,v])=>[k,v*2])),opaqueTop:200});
assert(Math.abs(fit.placedFaceW-enlarged.placedFaceW)<1e-6);
const closer=planPortraitUniformFit({...input,frame:{...input.frame,w:1050}});
assert(closer.placedFaceW>=fit.placedFaceW);
for(let i=0;i<10;i++)assert.deepEqual(planPortraitUniformFit(input),fit);
assert.throws(()=>measureUniformAnchors(new Uint8ClampedArray(300*400*4),300,400));
assert.throws(()=>planPortraitUniformFit({...input,face:{...input.face,faceWidth:NaN}}));
console.log('PASS: garment anchors, centering, crown clearance, upload-resolution independence, garment distance and repeat stability.');
