import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('../src/studio-rights-dialog.jsx',import.meta.url),'utf8');
const summary=new Function(code.slice(code.indexOf('export function rightsSummary'),code.indexOf('export function StudioRightsDialog')).replace('export ','')+';return rightsSummary')();
assert.deepEqual(summary({processRemaining:2,generationRemaining:2,hairRemaining:2,trialAvailable:true,trialRemaining:1}),{credits:2,trial:'∞'});
assert.deepEqual(summary({processRemaining:0,trialAvailable:true,trialRemaining:2}),{credits:0,trial:'∞'});
assert.deepEqual(summary({processRemaining:3,trialAvailable:false,trialRemaining:2}),{credits:3,trial:'∞'});
assert.deepEqual(summary({processRemaining:-1.4,trialAvailable:false,trialRemaining:0}),{credits:0,trial:'∞'});
assert.deepEqual(summary({processRemaining:0},true),{credits:'∞',trial:'∞'});
const editor=await readFile(new URL('../src/studio-editor.jsx',import.meta.url),'utf8');
assert.equal(editor.split('onRights={onOpenRights||onRequestUnlock}').length-1,2);
assert(editor.includes('if(closeCropOnPurchase)setDownloadCrop(null);onRequestUnlock?.()'));
const main=await readFile(new URL('../src/main.jsx',import.meta.url),'utf8');
assert(main.includes('onOpenRights={()=>setRightsOpen(true)}'));
assert(main.includes("onPackages={()=>{setRightsOpen(false);setPayMsg('');setBuyOpen(true)}}"));
console.log('PASS: exact wallet download credit count without double-counting, unlimited free generation, private mode, both Studio menus open rights, packages remain an explicit action.');
