import test from 'node:test';
import assert from 'node:assert/strict';
import sharp from 'sharp';
import {readFile} from 'node:fs/promises';
import {createThaiAdaptiveComposition} from '../thai-adaptive-composition.js';
test('new upright neck guide moves the same-sized identity upward while native garment framing stays exact',async()=>{
 const outfit=await readFile(new URL('../public/assets/government-uniforms/female-operational.png',import.meta.url));
 const identity=await sharp({create:{width:120,height:180,channels:3,background:{r:201,g:96,b:74}}}).png().toBuffer();
 const args={outfit,identity,evidence:{version:1,faceAspect:1.48,jawRatio:.75,eyeRatio:.53},gender:'female'};
 const old=await createThaiAdaptiveComposition(args),legacy=await createThaiAdaptiveComposition({...args,uprightNeck:false}),next=await createThaiAdaptiveComposition({...args,uprightNeck:true});
 assert(old.equals(legacy),'Unopted legacy guides remain exact');assert(!next.equals(old));
 const decode=b=>sharp(b).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const [a,b]=await Promise.all([decode(old),decode(next)]);assert.deepEqual(a.info,b.info);
 const width=a.info.width,height=a.info.height,row=width*4;
 assert(a.data.subarray(Math.floor(height*.55)*row).equals(b.data.subarray(Math.floor(height*.55)*row)),'Lower garment pixels and frame cannot move');
 const bounds=d=>{let left=width,right=-1,top=height,bottom=-1;for(let y=0;y<height;y++)for(let x=0;x<width;x++){const i=(y*width+x)*4;if(Math.abs(d[i]-201)<2&&Math.abs(d[i+1]-96)<2&&Math.abs(d[i+2]-74)<2){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y)}}return {left,right,top,bottom}};
 const original=bounds(a.data),upright=bounds(b.data);assert(original.right>original.left&&upright.right>upright.left);
 assert.equal(upright.left,original.left);assert.equal(upright.right,original.right);assert.equal(upright.bottom-upright.top,original.bottom-original.top);
 assert(upright.bottom<original.bottom-20,'New visible neck gap must increase at actual guide resolution');
});
